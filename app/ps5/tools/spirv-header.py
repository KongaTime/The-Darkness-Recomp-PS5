#!/usr/bin/env python3
"""Wrap compiled SPIR-V modules in a C++ header the title links.

The console has no shader compiler at run time and no filesystem to load
modules from: RADV takes SPIR-V, so each module is built by glslang at build
time and embedded as words.

    spirv-header.py OUTPUT 'kMeshVertex=mesh.vert.spv' 'kMeshAlpha=mesh_alpha.frag.spv'
"""
import struct
import sys
from pathlib import Path

MAGIC = 0x07230203


def read_words(path: Path) -> list[int]:
    data = path.read_bytes()
    if len(data) < 20 or len(data) % 4:
        raise SystemExit(f"{path}: not a whole number of SPIR-V words")
    words = list(struct.unpack(f"<{len(data) // 4}I", data))
    if words[0] != MAGIC:
        raise SystemExit(f"{path}: bad SPIR-V magic 0x{words[0]:08X}")
    return words


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        raise SystemExit(__doc__)
    output = Path(argv[1])
    modules = []
    for argument in argv[2:]:
        name, separator, path = argument.partition("=")
        if not separator or not name.startswith("k"):
            raise SystemExit(f"expected NAME=path with a k-prefixed name, got {argument!r}")
        modules.append((name, read_words(Path(path))))

    lines = [
        "// Generated by app/ps5/tools/spirv-header.py. Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace DarkRecomp::Ps5::Shaders {",
    ]
    for name, words in modules:
        lines.append(f"inline constexpr uint32_t {name}[] = {{")
        for start in range(0, len(words), 8):
            row = "    " + " ".join(f"0x{word:08x}," for word in words[start:start + 8])
            lines.append(row)
        lines.append("};")
        lines.append("")
    lines.append("} // namespace DarkRecomp::Ps5::Shaders")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    total = sum(len(words) for _, words in modules)
    print(f"{output}: {len(modules)} module(s), {total} words")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
